"""## 7. Verificación de métricas desde las predicciones exportadas"""

import pandas as pd
from sklearn.metrics import accuracy_score, precision_recall_fscore_support
from pathlib import Path
ruta = Path("predicciones_modelos.csv")
df = pd.read_csv(ruta)
for modelo, g in df.groupby("modelo", sort=False):
    precision, recall, f1, _ = precision_recall_fscore_support(g.real, g.prediccion, labels=["NEG","NEU","POS"], average="macro", zero_division=0)
    print(modelo, "accuracy", round(accuracy_score(g.real, g.prediccion), 4), "precision", round(precision,4), "recall", round(recall,4), "f1", round(f1,4))